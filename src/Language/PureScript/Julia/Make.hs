{-# LANGUAGE OverloadedStrings #-}

-- |
-- Build orchestration for the Julia backend.
--
-- Reads @corefn.json@ for every compiled module, emits one Julia module
-- file per PureScript module, the runtime, the built-in FFI shims, a
-- topologically-ordered @loader.jl@, and (when a Main module exists) a
-- @main.jl@ entry point so the program runs with
-- @julia OUTPUT_DIR\/main.jl@.
--
module Language.PureScript.Julia.Make
  ( compile
  , CompileOptions(..)
  ) where

import Prelude

import Control.Monad (forM, forM_, unless, when)
import Data.Aeson (decodeFileStrict)
import Data.Aeson.Types (parseMaybe)
import Data.List (find)
import qualified Data.Map.Strict as Map
import Data.Maybe (catMaybes)
import qualified Data.Set as Set
import qualified Data.Text as T
import qualified Data.Text.IO as TIO
import System.Directory (createDirectoryIfMissing, doesFileExist, copyFile)
import System.FilePath ((</>), takeFileName, dropExtension)
import System.FilePath.Glob (glob)

import qualified Language.PureScript as P
import qualified Language.PureScript.CoreFn as CoreFn
import qualified Language.PureScript.CoreFn.FromJSON as CoreFn

import Language.PureScript.Julia.CodeGen (generateModuleJl)
import Language.PureScript.Julia.CodeGen.Common (jlModuleName, jlModuleAlias, jlFileName, jlForeignFileName)
import Language.PureScript.Julia.Foreigns (builtinForeigns)

data CompileOptions = CompileOptions
  { inputDir :: FilePath    -- ^ Directory containing corefn.json files (usually "output")
  , outputDir :: FilePath   -- ^ Directory for Julia output (usually "output-jl")
  }

-- | Compile all modules in the input directory
compile :: CompileOptions -> IO ()
compile opts = do
  let coreFnGlob = inputDir opts </> "*" </> "corefn.json"
  corefnFiles <- glob coreFnGlob

  when (null corefnFiles) $
    putStrLn "No corefn.json files found. Run 'spago build' (with a backend configured) first."

  unless (null corefnFiles) $ do
    putStrLn $ "Found " ++ show (length corefnFiles) ++ " modules to compile"
    createDirectoryIfMissing True (outputDir opts)

    -- Parse all modules up front (we need the import graph for the loader)
    mods <- fmap catMaybes . forM corefnFiles $ \corefnFile -> do
      mJson <- decodeFileStrict corefnFile
      case mJson >>= parseMaybe CoreFn.moduleFromJSON of
        Nothing -> do
          putStrLn $ "Error: failed to parse " ++ corefnFile
          return Nothing
        Just (_version, cfModule) -> return (Just cfModule)

    -- Emit each module
    forM_ mods $ \cfModule -> do
      let mn = CoreFn.moduleName cfModule
          outFile = outputDir opts </> jlFileName mn
      TIO.writeFile outFile (moduleFile cfModule)
      putStrLn $ "Compiled: " ++ T.unpack (jlModuleName mn)

    -- Runtime + built-in FFI shims; user shims copied last so they win.
    -- User foreigns are resolved per-module: co-located next to the .purs
    -- (via CoreFn modulePath) first, then the legacy ffi-jl/ dir as fallback.
    generateRuntime (outputDir opts)
    forM_ builtinForeigns $ \(name, content) ->
      TIO.writeFile (outputDir opts </> name) content
    forM_ mods (copyUserForeign (outputDir opts))

    -- Warn about reachable modules with foreign imports but no shim on disk
    let mainMod = find (\m -> CoreFn.moduleName m == P.ModuleName "Main") mods
        ordered = loadOrder mods mainMod
        byName = Map.fromList [(CoreFn.moduleName m, m) | m <- mods]
    forM_ ordered $ \mn ->
      forM_ (Map.lookup mn byName) $ \m ->
        unless (null (CoreFn.moduleForeign m)) $ do
          let shim = outputDir opts </> jlForeignFileName mn
          exists <- doesFileExist shim
          unless exists $
            putStrLn $ "Warning: " ++ T.unpack (jlModuleName mn)
                     ++ " has foreign imports but no " ++ takeFileName shim
                     ++ " - provide one in ffi-jl/"

    -- Loader (deps-first include order) and entry point
    TIO.writeFile (outputDir opts </> "loader.jl") (loaderFile mods ordered byName)
    case mainMod of
      Just _ -> do
        TIO.writeFile (outputDir opts </> "main.jl") $ T.unlines
          [ "# Generated by purejl - program entry point"
          , "include(\"loader.jl\")"
          , "Main_.main()"
          ]
        putStrLn $ "Run with: julia " ++ (outputDir opts </> "main.jl")
      Nothing ->
        putStrLn "No Main module found - generated loader.jl only"

    putStrLn "Done!"

-- | Full text of one generated module file
moduleFile :: CoreFn.Module CoreFn.Ann -> T.Text
moduleFile cfModule =
  let mn@(P.ModuleName name) = CoreFn.moduleName cfModule
      isPrimModule (P.ModuleName n) = T.isPrefixOf "Prim" n
      imports = dedupe
        [ depMn
        | depMn <- map snd (CoreFn.moduleImports cfModule)
        , depMn /= mn
        , not (isPrimModule depMn)
        ]
      hasForeign = not (null (CoreFn.moduleForeign cfModule))
  in T.unlines $
       [ "# Generated by purejl from PureScript module: " <> name
       , "# Do not edit this file directly"
       , "module " <> jlModuleName mn
       , "import ..PurejlRuntime: _runtime_lazy, _js_number_string, PSData, PSEff"
       ]
         -- Aliased into the reserved module namespace so a user identifier
         -- cannot collide with an imported module (tests/purs/passing/4174).
       ++ [ "import .." <> jlModuleName depMn <> " as " <> jlModuleAlias depMn
          | depMn <- imports ]
       ++ (if hasForeign
             then [ "include(\"" <> T.pack (jlForeignFileName mn) <> "\")" ]
             else [])
       ++ [ "" , generateModuleJl cfModule , "end" ]

dedupe :: Ord a => [a] -> [a]
dedupe = go Set.empty
  where
    go _ [] = []
    go seen (x:xs)
      | x `Set.member` seen = go seen xs
      | otherwise = x : go (Set.insert x seen) xs

-- | Topologically-ordered module list (dependencies first). When a Main
-- module exists, restrict to its transitive closure; otherwise load
-- everything.
loadOrder :: [CoreFn.Module CoreFn.Ann] -> Maybe (CoreFn.Module CoreFn.Ann) -> [P.ModuleName]
loadOrder mods mainMod =
  let compiled = Set.fromList (map CoreFn.moduleName mods)
      depsOf = Map.fromList
        [ ( CoreFn.moduleName m
          , dedupe [ d | d <- map snd (CoreFn.moduleImports m)
                       , d /= CoreFn.moduleName m
                       , d `Set.member` compiled ] )
        | m <- mods ]
      roots = case mainMod of
        Just m -> [CoreFn.moduleName m]
        Nothing -> map CoreFn.moduleName mods
      -- DFS post-order: dependencies emitted before dependents
      visit (visited, acc) mn
        | mn `Set.member` visited = (visited, acc)
        | otherwise =
            let (visited', acc') =
                  foldl visit (Set.insert mn visited, acc)
                        (Map.findWithDefault [] mn depsOf)
            in (visited', acc' ++ [mn])
  in snd (foldl visit (Set.empty, []) roots)

-- | The loader: runtime first, then modules deps-first
loaderFile :: [CoreFn.Module CoreFn.Ann]
           -> [P.ModuleName]
           -> Map.Map P.ModuleName (CoreFn.Module CoreFn.Ann)
           -> T.Text
loaderFile _mods ordered _byName = T.unlines $
  [ "# Generated by purejl - includes all modules in dependency order"
  , "include(\"purejl_runtime.jl\")"
  ]
  ++ [ "include(\"" <> T.pack (jlFileName mn) <> "\")" | mn <- ordered ]

-- | Copy the user-supplied FFI shim for a single module into the output
-- directory, named for the module's @include@ target (@jlForeignFileName@).
--
-- Resolution order, matching how purs locates a co-located @Foo.js@:
--
--   1. Co-located next to the @.purs@: @dropExtension (modulePath m) <> ".jl"@
--      (e.g. @src\/Runtime.purs@ -> @src\/Runtime.jl@). The backend is invoked
--      from the project root, so the relative @modulePath@ resolves directly.
--   2. Fallback to the legacy flat @ffi-jl\/\<jlForeignFileName mn>@ directory,
--      preserving back-compat for the examples and the conformance suite.
--
-- Modules with no foreign imports are skipped.
copyUserForeign :: FilePath -> CoreFn.Module CoreFn.Ann -> IO ()
copyUserForeign outDir m =
  when (not (null (CoreFn.moduleForeign m))) $ do
    let mn = CoreFn.moduleName m
        dest = outDir </> jlForeignFileName mn
        colocated = dropExtension (CoreFn.modulePath m) <> ".jl"
        ffiFallback = "ffi-jl" </> jlForeignFileName mn
    coloExists <- doesFileExist colocated
    if coloExists
      then do
        copyFile colocated dest
        putStrLn $ "FFI (user, co-located): " ++ takeFileName colocated
      else do
        fallbackExists <- doesFileExist ffiFallback
        when fallbackExists $ do
          copyFile ffiFallback dest
          putStrLn $ "FFI (user, ffi-jl): " ++ takeFileName ffiFallback

-- | Runtime support module
generateRuntime :: FilePath -> IO ()
generateRuntime dir = TIO.writeFile (dir </> "purejl_runtime.jl") $ T.unlines
  [ "# PureScript Julia Runtime"
  , "# Generated by purejl"
  , "module PurejlRuntime"
  , ""
  , "export _runtime_lazy, _js_number_string, _int32, _int_div, _zshr, PSData, PSEff"
  , ""
  , "# Constructor values (ADR-0001, revised 2026-10). One concrete, NON-parametric"
  , "# type at every depth: a Julia tuple's type contains its fields' types, so a"
  , "# tag-tuple `Cons` cell had a type as long as the list, and Julia compiled a"
  , "# fresh specialisation for every length (TCOCase timed out; a 400-element"
  , "# List fold took 235 s on first call). Every field is `Any`, so the"
  , "# struct's type never grows. Indexing is kept -- tag at [1], field i at"
  , "# [i+1] -- so generated pattern matches and user FFI read it as before."
  , "# ONE concrete type for every constructor, so a dispatch site that sees Nil"
  , "# and Cons stays monomorphic (one struct per arity measured slower for that"
  , "# reason). Up to three fields are stored inline -- one allocation for"
  , "# Just/Cons/Tuple/Loop -- and the rest, rarely needed, in a Tuple."
  , "struct PSData"
  , "    tag::Base.String"
  , "    n::Base.Int"
  , "    f1::Any"
  , "    f2::Any"
  , "    f3::Any"
  , "    rest::Base.Tuple"
  , "end"
  , "Base.getindex(d::PSData, i::Base.Int) = i == 1 ? d.tag : i == 2 ? d.f1 : i == 3 ? d.f2 : i == 4 ? d.f3 : d.rest[i - 4]"
  , "Base.length(d::PSData) = d.n + 1"
  , "_psfields(d::PSData) = Base.ntuple(i -> d[i + 1], d.n)"
  , "Base.:(==)(a::PSData, b::PSData) = a.tag == b.tag && _psfields(a) == _psfields(b)"
  , "Base.hash(d::PSData, h::Base.UInt) = Base.hash(_psfields(d), Base.hash(d.tag, h))"
  , "# From a tuple of fields: what backend-jl emits, and convenient for FFI."
  , "PSData(tag, fs::Base.Tuple) = (n = Base.length(fs); PSData(tag, n, n >= 1 ? fs[1] : nothing, n >= 2 ? fs[2] : nothing, n >= 3 ? fs[3] : nothing, n > 3 ? fs[4:end] : ()))"
  , ""
  , "# Effect and ST values built by bind. Same mechanism as PSData: a"
  , "# closure's type contains its captures' types, so `bindE` chaining closures"
  , "# nested the type one level per iteration of a recursive Effect loop (1,000"
  , "# iterations took 14 s, almost all of it compilation). Boxing the closure in"
  , "# a struct with an `Any` field erases the nesting. Callable like the closure"
  , "# it wraps, so every consumer that runs an effect with `eff()` is unchanged,"
  , "# and pure/map and the other shims, which return bare closures, interoperate:"
  , "# only bind captures an effect, so only bind can nest (boxing pure/map as well"
  , "# cost +50% on a tight loop for nothing; ADR-0001, 2026-10 amendment)."
  , "struct PSEff"
  , "    f::Any"
  , "end"
  , "(e::PSEff)() = e.f()"
  , ""
  , "# JS int32 semantics, for the operators the optimizer lowers directly"
  , "# (Data.Int.Bits complement and shifts). Ordinary Int arithmetic does NOT"
  , "# wrap -- Jurist's Int is Int64 by ADR-0001 -- so these are used only where"
  , "# the laws demand JS ToInt32, and they hold exactly the semantics the"
  , "# Data_Int_Bits and Data_EuclideanRing shims hold for the oracle lane."
  , "_int32(n) = Base.Int(Base.reinterpret(Base.Int32, Base.UInt32(Base.mod(n, 4294967296))))"
  , "_zshr(n1, n2) = Base.Int(Base.reinterpret(Base.UInt32, Base.Int32(_int32(n1))) >> (n2 & 31))"
  , "# Euclidean division, matching Data_EuclideanRing_foreign.intDiv. A function"
  , "# rather than an inlined conditional so the divisor is evaluated once."
  , "_int_div(x, y) = y == 0 ? 0 : Base.fld(x, y)"
  , ""
  , "# JS Number.prototype.toString formatting, built on Julia's shortest-"
  , "# roundtrip repr (same digits, different placement rules). Decimal"
  , "# notation for 1e-6 <= |n| < 1e21, exponential with explicit sign"
  , "# otherwise, integer-valued doubles without a point. Used by the"
  , "# Data.Show and Data.Number.Format shims."
  , "function _js_number_string(n)"
  , "    # Coerce FIRST. A PureScript Number is an IEEE double, but one that"
  , "    # crossed an FFI seam may arrive as something that IS a real number"
  , "    # without BEING a Float64 -- and Julia has more of those than any"
  , "    # other runtime we target: Float32 (ubiquitous in imaging, GPU and ML"
  , "    # libraries), Float16, BigFloat, Rational, Integer."
  , "    #"
  , "    # `Base.string` renders each in ITS OWN notation, and the"
  , "    # digit-placement code below then strips `.` out of the mantissa, so"
  , "    # the damage is silent and total:"
  , "    #"
  , "    #     Float32(0.1)  -> \"0.1\"     but the double it denotes is"
  , "    #                                0.10000000149011612"
  , "    #     1//2          -> \"1//2\"    which is not a number at all"
  , "    #     BigFloat(0.1) -> 79 digits"
  , "    #"
  , "    # Sibling of the same fix in purepy's runtime, where numpy 2.x"
  , "    # changing scalar `repr` made `show 399.7569` print 3997569. Pythia"
  , "    # found it by a checksum gate in perf-seam; Jurist inherited the"
  , "    # hazard and was fixed by audit rather than by being bitten."
  , "    n = Base.Float64(n)"
  , "    if Base.isnan(n); return \"NaN\"; end"
  , "    if n == Base.Inf; return \"Infinity\"; end"
  , "    if n == -Base.Inf; return \"-Infinity\"; end"
  , "    if n == 0.0; return \"0\"; end"
  , "    s = Base.string(n)"
  , "    neg = Base.startswith(s, \"-\")"
  , "    if neg; s = s[2:end]; end"
  , "    parts = Base.split(s, \"e\")"
  , "    mant = parts[1]"
  , "    ex = Base.length(parts) == 2 ? Base.parse(Base.Int, parts[2]) : 0"
  , "    dot = Base.findfirst('.', mant)"
  , "    intlen = dot === nothing ? Base.length(mant) : dot - 1"
  , "    digits = Base.replace(mant, \".\" => \"\")"
  , "    pp = intlen + ex      # decimal point position: n = 0.digits * 10^pp"
  , "    k0 = Base.length(digits)"
  , "    digits = Base.lstrip(digits, '0')"
  , "    pp -= k0 - Base.length(digits)"
  , "    digits = Base.rstrip(digits, '0')"
  , "    k = Base.length(digits)"
  , "    body = if k <= pp <= 21"
  , "        digits * Base.repeat(\"0\", pp - k)"
  , "    elseif 0 < pp <= 21"
  , "        digits[1:pp] * \".\" * digits[(pp + 1):end]"
  , "    elseif -6 < pp <= 0"
  , "        \"0.\" * Base.repeat(\"0\", -pp) * digits"
  , "    else"
  , "        e = pp - 1"
  , "        Base.string(digits[1]) * (k > 1 ? \".\" * digits[2:end] : \"\") *"
  , "            \"e\" * (e >= 0 ? \"+\" : \"-\") * Base.string(Base.abs(e))"
  , "    end"
  , "    neg ? \"-\" * body : body"
  , "end"
  , ""
  , "# Lazy initialization wrapper for mutually recursive top-level bindings."
  , "# state: 0 = uninitialized, 1 = initializing, 2 = done"
  , "function _runtime_lazy(name, module_name, init)"
  , "    state = Base.Ref(0)"
  , "    val = Base.Ref{Any}(nothing)"
  , "    function thunk()"
  , "        if state[] == 2"
  , "            return val[]"
  , "        end"
  , "        if state[] == 1"
  , "            Base.error(name * \" was needed before it finished initializing (module \" * module_name * \")\")"
  , "        end"
  , "        state[] = 1"
  , "        val[] = init()"
  , "        state[] = 2"
  , "        val[]"
  , "    end"
  , "    thunk"
  , "end"
  , ""
  , "end"
  ]
